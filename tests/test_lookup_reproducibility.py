"""Build artifacts must not depend on Python's per-process hash seed."""

import hashlib
import json
import os
from pathlib import Path
import sqlite3
import subprocess
import sys


ROOT = Path(__file__).resolve().parents[1]


def test_lookup_build_is_identical_across_hash_seeds(tmp_path):
    data = tmp_path / "data"
    data.mkdir()
    sources = {
        "ag_lookup.json": {"λόγος": "λόγος", "λέγει": "λέγω",
                           "ἀπῇμεν": "ἀπέρχομαι", "Ἀπῇμεν": "ἀπέρχομαι",
                           "ᾖμεν": "ἔρχομαι", "ἐξῇμεν": "ἐξέρχομαι",
                           "ᾖσαν": "ἀείδω", "ἴσθι": "εἰμί",
                           "ἀπῆμεν": "ἄπειμι",
                           "μοναχικός": "μοναχικός", "μοναχικοῦ": "μοναχικός"},
        "grc_ikos_adjectives.json": {"lemmas": [
            {"lemma": "μοναχικός", "evidence": ["sophocles"]}]},
        "mg_lookup.json": {"λόγος": "λόγος", "λέει": "λέω", "λέγει": "λέω"},
        "med_lookup.json": {},
        "vlg_headwords.json": ["ἀρχή", "βίος", "γῆ", "δῶρον", "ἔργον"],
        "wip_headwords.json": ["ζυγόν", "ἦθος", "θεός", "ἰδέα", "κόσμος"],
        "lsj10_headwords.json": ["λίθος", "μέτρον", "νόμος", "ὁδός", "πῦρ"],
        "lbg_headwords.json": [{"lemma": word} for word in
                               ("ῥόδον", "σῶμα", "τέλος", "ὕδωρ", "φῶς")],
        "lbg_pairs.json": {"ῥόδα": "ῥόδον", "σώματος": "σῶμα",
                           "Ῥώμης": "Ῥώμη"},
        "etymology_bridges.json": {"λέω": ["λέγω"], "λόγος": ["λόγος"]},
        "related_lemmas.json": {"λέγω": ["λόγος"]},
    }
    for name, value in sources.items():
        (data / name).write_text(json.dumps(value, ensure_ascii=False))
    (data / "lookup_sources.json").write_bytes(
        (ROOT / "data" / "lookup_sources.json").read_bytes())

    # Run the real builder with only the small fixture available. Redirect
    # all its inputs, outputs and audit report; no production data is read
    # or overwritten by this test.
    script = """
from functools import partial
from pathlib import Path
import sys
import build_lookup_db as builder

data = Path(sys.argv[1])
original_data = builder.DATA_DIR
def relocate(value):
    if isinstance(value, Path) and value.parent == original_data:
        return data / value.name
    if isinstance(value, (tuple, list)):
        return type(value)(relocate(item) for item in value)
    return value
for name, value in list(vars(builder).items()):
    setattr(builder, name, relocate(value))
builder.DATA_DIR = data
builder._write_citation_rejection_report = partial(
    builder._write_citation_rejection_report,
    path=builder.CITATION_REJECTIONS_PATH,
)
builder.build()
"""
    results = []
    for seed in (1, 17, 73):
        result = subprocess.run(
            [sys.executable, "-c", script, str(data)], cwd=ROOT,
            env={**os.environ, "PYTHONHASHSEED": str(seed)},
            capture_output=True, text=True, timeout=30,
        )
        assert result.returncode == 0, result.stdout + result.stderr
        results.append({
            name: hashlib.sha256((data / name).read_bytes()).hexdigest()
            for name in ("lookup.db", "spell_index.db",
                         "citation_hygiene_rejections.tsv")
        })
    assert results[1:] == results[:-1]

    # Verify that all four independent headword sources actually took part,
    # and that language-specific rows and bridge tables were built as well.
    with sqlite3.connect(data / "lookup.db") as conn:
        rows = dict(conn.execute(
            "SELECT form, lemmas.text FROM lookup JOIN lemmas "
            "ON lookup.lemma_id = lemmas.id WHERE lang = 'all'"
        ))
        assert rows["ἀπῇμεν"] == rows["Ἀπῇμεν"] == rows["ἀπῆμεν"] == "ἄπειμι"
        assert rows["ᾖμεν"] == "εἶμι" and rows["ἐξῇμεν"] == "ἔξειμι"
        assert rows["ᾖσαν"] == "ἀείδω" and rows["ἴσθι"] == "εἰμί"
        # The default citation remains independent of the complete analysis
        # set. A future rebuild must not discard ambiguity or its evidence.
        readings = json.loads(conn.execute(
            "SELECT readings FROM grammatical_readings WHERE form = ?", ("ᾖσαν",)
        ).fetchone()[0])
        assert {r["lemma"] for r in readings} == {"εἶμι", "οἶδα", "ἀείδω"}
        assert {r["lemma"]: r["analyses"][0]["tense"] for r in readings} == {
            "εἶμι": "imperfect", "οἶδα": "pluperfect", "ἀείδω": "aorist"}
        assert all(r["evidence"] for r in readings)
        for name in ("vlg_headwords.json", "wip_headwords.json",
                     "lsj10_headwords.json"):
            assert all(rows[word] == word for word in sources[name])
        assert all(rows[row["lemma"]] == row["lemma"]
                   for row in sources["lbg_headwords.json"])
        # A generated Byzantine form keeps its accents and also answers
        # unaccented input.
        assert rows["ῥόδα"] == rows["ροδα"] == "ῥόδον"
        assert rows["σώματος"] == rows["σωματος"] == "σῶμα"
        assert rows["Ῥώμης"] == rows["Ρωμης"] == rows["ρωμης"] == "Ῥώμη"
        assert rows["Ρωμη"] == rows["ρωμη"] == "Ῥώμη"
        # The file says what built it and what it holds, and a lemma's
        # forms are read through an index.
        import build_lookup_db
        # Every row names the source of its reading, and the registry rides
        # along with each source's licenses.
        origin = dict(conn.execute(
            "SELECT form || '|' || lang, s.code FROM lookup l "
            "JOIN sources s ON s.id = l.source_id"))
        assert conn.execute("SELECT count(*) FROM lookup WHERE source_id NOT IN "
                            "(SELECT id FROM sources)").fetchone()[0] == 0
        assert origin["ἀπῆμεν|all"] == "wiktionary_grc"
        # A listed -ικός adjective gains its feminine cells, under their source.
        assert rows["μοναχικήν"] == rows["μοναχικην"] == rows["μοναχικαί"] == "μοναχικός"
        assert origin["μοναχικήν|all"] == "grc_adjective_gaps"
        assert origin["μοναχικοῦ|all"] == "wiktionary_grc"
        assert origin["λέει|all"] == "wiktionary_el"
        assert origin["ῥόδα|all"] == origin["ροδα|all"] == "lbg_generated"
        assert origin["ῥόδον|all"] == "lbg_headwords"
        assert {origin[f"{word}|all"] for word in sources["vlg_headwords.json"]
                if f"{word}|all" in origin} <= {"vlg_headwords", "wiktionary_grc"}
        registry, _ = build_lookup_db.load_lookup_sources(data / "lookup_sources.json")
        stored = {code: (share, json.loads(parts)) for code, share, parts in conn.execute(
            "SELECT code, share_alike, components FROM sources")}
        assert set(stored) == {source["code"] for source in registry}
        assert stored["diorisis"][0] == 0 and stored["wiktionary_grc"][0] == 1
        assert all(part["license"] for _, parts in stored.values() for part in parts)
        meta = dict(conn.execute("SELECT key, value FROM meta"))
        assert len(meta["sources_sha256"]) == 64
        assert meta["schema_version"] == str(build_lookup_db.LOOKUP_SCHEMA_VERSION)
        assert meta["dilemma_version"] == (ROOT / "VERSION").read_text().strip()
        assert int(meta["lookup_rows"]) == conn.execute(
            "SELECT count(*) FROM lookup").fetchone()[0]
        assert int(meta["lemmas"]) == conn.execute(
            "SELECT count(*) FROM lemmas").fetchone()[0]
        assert meta["lookup_sha256"] == build_lookup_db.lookup_content_sha256(conn)
        plan = " ".join(row[3] for row in conn.execute(
            "EXPLAIN QUERY PLAN SELECT form FROM lookup WHERE lemma_id = 1"))
        assert "idx_lookup_lemma" in plan
        assert conn.execute("SELECT count(*) FROM bridges").fetchone()[0] == 2
        assert conn.execute("SELECT count(*) FROM related_lemmas").fetchone()[0] == 1
        assert conn.execute(
            "SELECT lemmas.text FROM lookup JOIN lemmas "
            "ON lookup.lemma_id = lemmas.id WHERE form = ? AND lang = 'el'",
            ("λέγει",),
        ).fetchone() == ("λέω",)

    # A reading from an input the registry does not list stops the build, so
    # no row ships without a recorded source and license.
    registry = json.loads((data / "lookup_sources.json").read_text(encoding="utf-8"))
    for source in registry["sources"]:
        source["inputs"] = [label for label in source["inputs"]
                            if label != "mg_lookup.json"]
    (data / "lookup_sources.json").write_text(json.dumps(registry, ensure_ascii=False))
    result = subprocess.run([sys.executable, "-c", script, str(data)], cwd=ROOT,
                            capture_output=True, text=True, timeout=30)
    assert result.returncode != 0
    assert "mg_lookup.json" in result.stderr and "not in lookup_sources.json" in result.stderr


def test_lookup_source_registry_is_complete_and_unambiguous(tmp_path):
    import build_lookup_db
    sources, by_input = build_lookup_db.load_lookup_sources()
    assert {"ag_lookup.json", "mg_lookup.json", "lbg_pairs.json",
            "lookup_overrides", "el_paradigm_gaps"} <= by_input.keys()
    for source in sources:
        assert source["components"] and source["attribution"]

    def broken(change):
        registry = json.loads((ROOT / "data" / "lookup_sources.json").read_text())
        change(registry["sources"])
        path = tmp_path / "sources.json"
        path.write_text(json.dumps(registry, ensure_ascii=False))
        try:
            build_lookup_db.load_lookup_sources(path)
        except ValueError as error:
            return str(error)
        return None

    assert "twice" in broken(lambda s: s.append(dict(s[0])))
    assert "license" in broken(lambda s: s[0]["components"].append({"name": "x"}))
    assert "two sources" in broken(
        lambda s: s.append({**s[1], "code": "other", "inputs": ["ag_lookup.json"]}))
